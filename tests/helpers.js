import { deflateRawSync } from 'node:zlib';
import { crc32 } from '../js/areas/cockpit/zip.js';

// In-memory stand-in for window.localStorage.
export function memBackend(initial = {}) {
  const m = new Map(Object.entries(initial));
  return {
    getItem: k => (m.has(k) ? m.get(k) : null),
    setItem: (k, v) => { m.set(k, String(v)); },
    removeItem: k => { m.delete(k); },
    key: i => [...m.keys()][i] ?? null,
    get length() { return m.size; },
  };
}

// A ZIP with deflated entries and a choice of name bytes and flags, like other tools write them.
export function mkzip(files) {
  const parts = [], central = [];
  let off = 0;
  const enc = s => new TextEncoder().encode(s);
  for (const f of files) {
    const name = f.nameBytes || enc(f.name), raw = f.data, data = f.deflate ? deflateRawSync(raw) : raw;
    const flags = (f.utf8 ? 0x800 : 0) | (f.encrypted ? 1 : 0), method = f.method ?? (f.deflate ? 8 : 0);
    const lh = Buffer.alloc(30);
    lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(20, 4); lh.writeUInt16LE(flags, 6); lh.writeUInt16LE(method, 8);
    lh.writeUInt32LE(crc32(raw), 14); lh.writeUInt32LE(data.length, 18); lh.writeUInt32LE(raw.length, 22); lh.writeUInt16LE(name.length, 26);
    const ch = Buffer.alloc(46);
    ch.writeUInt32LE(0x02014b50, 0); ch.writeUInt16LE(20, 4); ch.writeUInt16LE(20, 6); ch.writeUInt16LE(flags, 8); ch.writeUInt16LE(method, 10);
    ch.writeUInt32LE(crc32(raw), 16); ch.writeUInt32LE(data.length, 20); ch.writeUInt32LE(raw.length, 24); ch.writeUInt16LE(name.length, 28); ch.writeUInt32LE(off, 42);
    parts.push(lh, Buffer.from(name), Buffer.from(data));
    central.push(ch, Buffer.from(name));
    off += 30 + name.length + data.length;
  }
  const cd = Buffer.concat(central), end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10); end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(off, 16);
  return new Uint8Array(Buffer.concat([...parts, cd, end]));
}
